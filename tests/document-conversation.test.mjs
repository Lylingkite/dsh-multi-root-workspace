import assert from 'node:assert/strict';
import { createDocumentationTurnCapture, validateConversationNotes, proposeConversationNotes } from '../document-conversation.js';
const capture=createDocumentationTurnCapture();
const session={header:{meta:{origin:'user'}}};
const subagent={header:{meta:{origin:'subagent'}}};
const ev=(type,data,seq)=>({type,data,seq});
const msg=(kind,text,seq)=>ev('user/message',{role:'user',source:{kind},content:[{type:'text',text}]},seq);
const begin=ev('turn/start',{turn:1});
const end=ev('turn/end',{turn:1,reason:{kind:'completed'}});
const quote='etmsGateway 调用 etms 的订单接口';
capture(session,begin); capture(subagent,begin);
for (const kind of ['goal','runtime-context','user-question-reply','tool','model']) capture(session,msg(kind,'不应写入',2));
capture(subagent,msg('user',quote,4));
assert.equal(capture(subagent,end),null);
capture(session,msg('user',quote,5));
const captured=capture(session,end);
assert.deepEqual(captured,{turn:1,messages:[{seq:5,text:quote}]});
assert.equal(capture(session,end),null);
const projects=[{id:'a',name:'etmsGateway'},{id:'b',name:'etms'},{id:'c',name:'et'}];
const row={kind:'relationship',projectId:'a',relatedId:'b',quote,seq:5};
assert.deepEqual(validateConversationNotes([row,row],captured,projects),[row]);
assert.deepEqual(validateConversationNotes([{...row,relatedId:'c'},{...row,seq:4},{...row,quote:quote+'编造'}],captured,projects),[]);
assert.deepEqual(validateConversationNotes([row],captured,[...projects,{id:'d',name:'ETMS'}]),[]);
capture(session,begin); capture(session,msg('user',quote,5));
assert.equal(capture(session,ev('turn/end',{turn:1,reason:{kind:'aborted'}})),null);
capture(session,begin); capture(session,msg('user','x'.repeat(12001),5));
assert.equal(capture(session,end),null);
assert.deepEqual(proposeConversationNotes(captured,projects),[row]);
assert.deepEqual(proposeConversationNotes({messages:[{seq:6,text:'etmsGateway 是否调用 etms？'}]},projects),[]);
assert.equal(proposeConversationNotes({messages:[{seq:6,text:'etms 负责订单管理'}]},projects)[0].kind,'role');
console.log('PASS: completed human turn capture, no synthetic inputs, validated original quotes and unambiguous project IDs');
